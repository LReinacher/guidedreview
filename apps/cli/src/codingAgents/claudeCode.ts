import path from "node:path";
import { claudeCliProvider, CLAUDE_COMMAND } from "../providers/claudeCli";
import { detectIfInstalled, parseJson, stringField } from "./parse";
import type { AgentIo, CodingAgentAdapter } from "./types";
import { unusableAuth } from "./types";

const DISPLAY_NAME = "Claude Code";

const NO_BINARY_REASON =
  "Claude Code is installed but `claude` is not on your PATH. Guided Review runs reviews through `claude -p`. Reinstall Claude Code, or set ANTHROPIC_API_KEY.";

function claudeHome(io: AgentIo): string {
  return io.env("CLAUDE_CONFIG_DIR") ?? path.join(io.homedir(), ".claude");
}

/** Claude Code's configured default model, so reviews match the user's setup. */
async function modelFromSettings(io: AgentIo): Promise<string | undefined> {
  const raw = await io.readFile(path.join(claudeHome(io), "settings.json"));
  const json = parseJson(raw);
  if (!json || typeof json !== "object") return undefined;
  return stringField((json as Record<string, unknown>).model);
}

async function installed(io: AgentIo): Promise<boolean> {
  if (await io.which(CLAUDE_COMMAND)) return true;
  if (await io.fileExists(path.join(io.homedir(), ".claude.json"))) return true;
  const home = claudeHome(io);
  return (
    (await io.fileExists(path.join(home, "settings.json"))) ||
    (await io.fileExists(path.join(home, ".credentials.json")))
  );
}

/**
 * Claude Code owns its own auth. A subscription login is stored as an OAuth
 * session (`sk-ant-oat01-…`) that api.anthropic.com rejects, so we do not read
 * the keychain or `.credentials.json` at all — reviews are generated by
 * spawning `claude -p`, which authenticates however the user signed in
 * (subscription or ANTHROPIC_API_KEY).
 *
 * A console API key on its own does not need this adapter: `resolveSettings`
 * picks up ANTHROPIC_API_KEY before any agent is considered.
 */
export const claudeCodeAdapter: CodingAgentAdapter = {
  id: "claude-code",
  displayName: DISPLAY_NAME,
  provider: "anthropic",
  reviewClient: claudeCliProvider,

  async detect(io) {
    return detectIfInstalled(this, io, installed);
  },

  async resolveAuth(io) {
    const model = await modelFromSettings(io);
    if (!(await io.which(CLAUDE_COMMAND))) {
      return unusableAuth("anthropic", NO_BINARY_REASON, { kind: "cli", model });
    }
    return {
      provider: "anthropic",
      model,
      // Nothing to carry: the binary holds the credential, not us.
      secret: "",
      kind: "cli",
      usableForReview: true,
    };
  },
};
